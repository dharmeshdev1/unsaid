#!/usr/bin/env python3
"""Regenerate crates/unsaid-lwe/src/gauss_table.rs with exact decimal arithmetic."""
from decimal import Decimal, getcontext
from pathlib import Path

getcontext().prec = 80
SIGMA = Decimal("6.4")
TAIL = 62

weights = [(-(Decimal(x * x)) / (2 * SIGMA * SIGMA)).exp() for x in range(-TAIL, TAIL + 1)]
total = sum(weights)
cumulative, table = Decimal(0), []
for weight in weights[:-1]:
    cumulative += weight / total
    table.append(int(cumulative * (Decimal(2) ** 64)))

rows = [
    "    " + " ".join(f"0x{v:016x}," for v in table[i : i + 4]) for i in range(0, len(table), 4)
]
body = "\n".join(rows)
out = Path(__file__).resolve().parent.parent / "crates/unsaid-lwe/src/gauss_table.rs"
out.write_text(
    f"""// Generated by tools/gen_gauss_table.py. Do not edit.
//
// `CDT[i]` is floor(2^64 * P[X <= i - TAIL]) for X a discrete Gaussian with sigma = 6.4,
// truncated to [-TAIL, TAIL]. The truncated mass is below 2^-64.

/// Largest magnitude the sampler can produce.
pub const TAIL: i32 = {TAIL};

/// Cumulative distribution table, one entry per value except the last.
pub const CDT: [u64; {len(table)}] = [
{body}
];
"""
)
